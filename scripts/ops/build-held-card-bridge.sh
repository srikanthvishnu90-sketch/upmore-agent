#!/bin/bash
# Builds the held live-apply files for the Messages card (20261021220430) and the card -> cloud bridge (20261024130000)
# from the migration files themselves, each one transaction that also writes its ledger row (sha256 of the file as
# committed). --check: exit 1 if the committed files differ from what this would write (drift).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
OUT="$ROOT/docs/apply/held-card-bridge"
CARD=20261021220430_career_apply_message_cards.sql
BRIDGE=20261024130000_career_apply_card_cloud_bridge.sql
sha() { sha256sum "$ROOT/supabase/migrations/$1" | cut -d' ' -f1; }
card() {
  echo "-- HELD. Generated by scripts/ops/build-held-card-bridge.sh from supabase/migrations/$CARD (sha256 $(sha $CARD))."
  echo "-- One transaction: the migration, then its ledger row. Run only on the owner's written word, after 01-preflight.sql."
  echo "begin;"
  cat "$ROOT/supabase/migrations/$CARD"
  echo "insert into public.upmore_migration_ledger(filename, sha256) values ('$CARD', '$(sha $CARD)');"
  echo "commit;"
}
bridge() {
  echo "-- HELD. Generated by scripts/ops/build-held-card-bridge.sh from supabase/migrations/$BRIDGE (sha256 $(sha $BRIDGE))."
  echo "-- The file owns BEGIN/COMMIT; its final COMMIT is preceded here by its ledger row, so both commit together."
  local body; body="$(cat "$ROOT/supabase/migrations/$BRIDGE")"
  [[ "$(tail -n1 <<<"$body")" == "commit;" ]] || { echo "bridge file no longer ends in commit;" >&2; exit 1; }
  head -n -1 <<<"$body"
  echo "insert into public.upmore_migration_ledger(filename, sha256) values ('$BRIDGE', '$(sha $BRIDGE)');"
  echo "commit;"
}
if [[ "${1:-}" == "--check" ]]; then
  diff -q <(card) "$OUT/02-apply-card.sql" >/dev/null && diff -q <(bridge) "$OUT/03-apply-bridge.sql" >/dev/null \
    || { echo "held apply files are stale: run scripts/ops/build-held-card-bridge.sh" >&2; exit 1; }
  echo "held apply files match the migrations"
else
  card > "$OUT/02-apply-card.sql"
  bridge > "$OUT/03-apply-bridge.sql"
  echo "wrote $OUT/02-apply-card.sql $OUT/03-apply-bridge.sql"
fi
