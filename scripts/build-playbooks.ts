// Compile supabase/functions/_shared/agent/knowledge/playbooks/*.md into playbooks.generated.ts.
//   deno run -A scripts/build-playbooks.ts          write the file
//   deno run -A scripts/build-playbooks.ts --check  exit 1 when the committed file is stale (the test runs the same check)
import { parsePlaybook } from "../supabase/functions/_shared/agent/knowledge/parse.ts";
const dir = new URL("../supabase/functions/_shared/agent/knowledge/", import.meta.url);

export function compile(): string {
  const files = [...Deno.readDirSync(new URL("playbooks/", dir))].filter((e) => e.name.endsWith(".md")).map((e) => e.name).sort();
  const books = files.map((f) => parsePlaybook(Deno.readTextFileSync(new URL(`playbooks/${f}`, dir)), f));
  const ids = new Set<string>();
  for (const b of books) { if (ids.has(b.id)) throw new Error(`duplicate id ${b.id}`); ids.add(b.id); }
  return `// GENERATED by scripts/build-playbooks.ts from knowledge/playbooks/*.md. Do not edit; edit the markdown and rebuild.\nimport type { Playbook } from "./parse.ts";\nexport const PLAYBOOKS: Playbook[] = ${JSON.stringify(books, null, 1)};\n`;
}
if (import.meta.main) {
  const out = new URL("playbooks.generated.ts", dir), text = compile();
  if (Deno.args.includes("--check")) {
    const have = (() => { try { return Deno.readTextFileSync(out); } catch { return ""; } })();
    if (have !== text) { console.error("playbooks.generated.ts is stale: run deno run -A scripts/build-playbooks.ts"); Deno.exit(1); }
  } else Deno.writeTextFileSync(out, text);
}
