// Feature 6: writes scripts/launch/schedule-career-ingest.sql from the measured lane plan
// (packages/career-data/ingest-lane-plan.json, written by scripts/career/measure-ingest-lane.ts --write): one pg_cron job
// per lane, each calling career-ingest every interval with ?lane=k&lanes=N&window_min=W, lanes staggered across the
// interval's minutes so they do not all start at once. tests/career-ingest-lanes.test.cjs fails while the file is stale.
//   node scripts/launch/build-ingest-schedule.cjs [--check]
"use strict";
const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "../..");
const PLAN = path.join(root, "packages/career-data/ingest-lane-plan.json");
const OUT = path.join(root, "scripts/launch/schedule-career-ingest.sql");

function scheduleSql(planFile) {
  const p = planFile.plan, m = planFile.measured;
  if (!p || !p.ok || !(p.lanes >= 1 && p.lanes <= 64)) throw new Error("the lane plan has no lane count");
  if (60 % p.interval_min !== 0 || p.interval_min > 30) throw new Error(`interval ${p.interval_min} min does not divide the hour`);
  const every = p.interval_min;
  return `-- The job-ingestion schedule (WO-006; Feature 6: hourly at scale). Generated by scripts/launch/build-ingest-schedule.cjs
-- from packages/career-data/ingest-lane-plan.json; do not edit by hand.
-- pg_cron calls career-ingest through pg_net once per lane every ${every} minutes with the CAREER_INGEST_SECRET header. The
-- secret lives in Vault and is read at call time, so it never appears in the job text, a command line or this file.
-- Run by the OWNER only, after the migrations and the function deploy:
--   CAREER_INGEST_SECRET=... psql "$SUPABASE_DB_URL" -v url=https://<ref>.supabase.co/functions/v1/career-ingest -f scripts/launch/schedule-career-ingest.sql
-- The same secret must be set on the function (supabase secrets set CAREER_INGEST_SECRET=... INGEST_CONTACT_EMAIL=...).
--
-- The plan (${planFile.directory_boards} boards; MEASURED ${m.cpuMsPerBoard} ms CPU per board on one lane of the offline fixtures,
-- ASSUMED ${planFile.assumed.latencyMs} ms per ATS request): ${p.lanes} lanes, each run reading up to ${p.capacity_per_run} boards
-- (${p.cpu_ms_per_run} ms CPU, ${p.wall_s_per_run} s wall; ${m.cpuMsPerBoardUnchanged} ms for a board whose body is unchanged, ASSUMED
-- ${planFile.assumed.changedShare * 100}% of boards change between reads); ${p.invocations_per_hour} function calls and about ${p.requests_per_hour} ATS requests an hour.
-- SIMULATED oldest read over 6 h: ${(planFile.simulated || []).map((r) => `${r.worst_age_min} min with ${r.lose * 100}% of runs lost and ${r.cut * 100}% cut short`).join("; ")}.
-- Lane k's URL carries ?lane=k&lanes=${p.lanes}&window_min=${p.window_min}&posting_budget=${p.posting_budget}; the handler takes those over its
-- env defaults. The posting budget bounds a run's CPU: once it has parsed that many postings it starts no more boards
-- (a board whose body is unchanged since its last read is not parsed). The first full read of every board takes about
-- ${p.first_coverage_hours} h at that bound; from then on every board is read within ${p.window_min} minutes.
-- Override with -v lanes=<n> (1..64) or -v window_min=<minutes> to run a different plan; re-running replaces every
-- ingest job (lanes beyond the new count are removed) and the secret.
-- Health: select * from public.career_ingest_coverage(interval '1 hour');  -- one row per lane, the last report each.
-- select last_run_at from public.career_ingest_state; older than 30 minutes means ingestion is down.
\\set ON_ERROR_STOP on
\\set secret \`printf '%s' "$CAREER_INGEST_SECRET"\`
\\if :{?lanes}
\\else
  \\set lanes ${p.lanes}
\\endif
\\if :{?window_min}
\\else
  \\set window_min ${p.window_min}
\\endif
\\if :{?posting_budget}
\\else
  \\set posting_budget ${p.posting_budget}
\\endif
select (:lanes)::int between 1 and 64 as lanes_ok, (:window_min)::int between 15 and 2880 as window_ok \\gset
\\if :lanes_ok
\\else
  \\echo 'lanes must be 1..64'
  \\quit 3
\\endif
\\if :window_ok
\\else
  \\echo 'window_min must be 15..2880'
  \\quit 3
\\endif
create extension if not exists pg_cron;
create extension if not exists pg_net;
select vault.create_secret(:'secret', 'trainee_career_ingest_secret', 'career-ingest scheduler header')
  where not exists (select 1 from vault.secrets where name = 'trainee_career_ingest_secret');
select vault.update_secret((select id from vault.secrets where name = 'trainee_career_ingest_secret'), :'secret');
-- Every earlier ingest job: the single job before Feature 6 and any lane of an earlier plan.
select cron.unschedule(jobname) from cron.job where jobname = 'trainee-career-ingest' or jobname like 'trainee-career-ingest-lane-%';
-- Lane 0 keeps the job name the smoke check reads (scripts/launch/trainee-smoke.cjs); minutes 2, 7, 12, ...
select cron.schedule('trainee-career-ingest', '2-59/${every} * * * *', format($job$
  select net.http_post(
    url := %L,
    headers := jsonb_build_object('content-type', 'application/json',
      'x-trainee-ingest-secret', (select decrypted_secret from vault.decrypted_secrets where name = 'trainee_career_ingest_secret')),
    body := '{}'::jsonb,
    timeout_milliseconds := 140000)
$job$, :'url' || '?lane=0&lanes=' || :lanes || '&window_min=' || :window_min || '&posting_budget=' || :posting_budget));
-- Lanes 1..N-1, staggered over the ${every} minutes of a cycle: lane k starts at minute (2 + k) mod ${every}.
select cron.schedule('trainee-career-ingest-lane-' || k, ((2 + k) % ${every}) || '-59/${every} * * * *', format($job$
  select net.http_post(
    url := %L,
    headers := jsonb_build_object('content-type', 'application/json',
      'x-trainee-ingest-secret', (select decrypted_secret from vault.decrypted_secrets where name = 'trainee_career_ingest_secret')),
    body := '{}'::jsonb,
    timeout_milliseconds := 140000)
$job$, :'url' || '?lane=' || k || '&lanes=' || :lanes || '&window_min=' || :window_min || '&posting_budget=' || :posting_budget))
from generate_series(1, (:lanes)::int - 1) k;
select jobname, schedule from cron.job where jobname = 'trainee-career-ingest' or jobname like 'trainee-career-ingest-lane-%' order by jobid;
`;
}

if (require.main === module) {
  const sql = scheduleSql(JSON.parse(fs.readFileSync(PLAN, "utf8")));
  if (process.argv.includes("--check")) {
    if (fs.readFileSync(OUT, "utf8") !== sql) { console.error("stale: run node scripts/launch/build-ingest-schedule.cjs"); process.exit(1); }
    console.log("schedule-career-ingest.sql matches the lane plan");
  } else { fs.writeFileSync(OUT, sql); console.log(`wrote ${path.relative(root, OUT)}`); }
}
module.exports = { scheduleSql, PLAN, OUT };
