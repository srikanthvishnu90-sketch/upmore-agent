#!/usr/bin/env node
// The owner's "Full Agent Capability List" (docs/capability-list/full-agent-capability-list-2026-10-11.md) against the
// code: every bullet's status is derived, not typed, from the registry and the reachable list in
// docs/capability-list/map.cjs. Writes docs/capability-list/README.md; --check fails on drift (a bullet added, removed or
// reordered, an unknown capability id, a stale report).
//   node scripts/capability-list.cjs [--check]
const fs = require("node:fs"), path = require("node:path");
const root = path.resolve(__dirname, "..");
const DOC = path.join(root, "docs/capability-list/full-agent-capability-list-2026-10-11.md");
const { REACHABLE, MAP, PARITY } = require(path.join(root, "docs/capability-list/map.cjs"));
const registry = JSON.parse(fs.readFileSync(path.join(root, "packages/capabilities/registry.json"), "utf8"));
const caps = Object.fromEntries(registry.capabilities.map(c => [c.id, c]));

function parse(text) {
  const out = []; let section = null, sub = null;
  for (const line of text.split("\n")) {
    const h2 = /^## (\d+)\. (.+)$/.exec(line); if (h2) { section = `${h2[1]}. ${h2[2]}`; sub = null; continue; }
    const h3 = /^### (.+)$/.exec(line); if (h3 && section) { sub = h3[1]; continue; }
    const b = /^- (.+?)\s*((?:\[(?:Read|Ask|Rule|Built in|Flag)\]\s*)+)$/.exec(line);
    if (b && section) out.push({ n: out.length + 1, section, sub, text: b[1], tags: b[2].match(/\[([^\]]+)\]/g).map(t => t.slice(1, -1)) });
  }
  return out;
}
// The status a person would see today, weakest claim wins: reachable in the product, a module that only passes offline
// tests, gated on a partner, or not built. PROVEN only when every capability is VERIFIED in the registry (none are).
function status(ids) {
  if (!ids.length) return "NOT_BUILT";
  const st = ids.map(id => caps[id].status);
  if (st.every(s => s === "VERIFIED")) return "PROVEN";
  if (ids.some(id => REACHABLE[id])) return "IN_PRODUCT";
  if (st.includes("TESTED")) return "MODULE_ONLY";
  if (st.includes("GATED")) return "GATED";
  return "NOT_BUILT";
}
function build() {
  const bullets = parse(fs.readFileSync(DOC, "utf8")), problems = [];
  if (bullets.length !== MAP.length) problems.push(`the doc has ${bullets.length} bullets, the map ${MAP.length}`);
  const rows = bullets.map((b, i) => {
    const m = MAP[i] || [];
    if (m[0] !== b.n) problems.push(`map entry ${i + 1} is numbered ${m[0]}`);
    const ids = String(m[1] || "").split(/\s+/).filter(Boolean);
    for (const id of ids) if (!caps[id]) problems.push(`bullet ${b.n}: unknown capability ${id}`);
    for (const id of Object.keys(REACHABLE)) if (!caps[id]) problems.push(`REACHABLE: unknown capability ${id}`);
    if (!["full", "part", "none"].includes(m[2])) problems.push(`bullet ${b.n}: coverage ${m[2]}`);
    if ((ids.length === 0) !== (m[2] === "none")) problems.push(`bullet ${b.n}: coverage "none" goes with no ids, and only then`);
    return Object.assign({}, b, { ids, coverage: m[2], note: m[3] || "", conflict: m[4] || null, status: ids.every(id => caps[id]) ? status(ids) : "?" });
  });
  return { rows, problems };
}
const ORDER = ["PROVEN", "IN_PRODUCT", "MODULE_ONLY", "GATED", "NOT_BUILT"];
function render(rows) {
  const by = (list, st) => list.filter(r => r.status === st).length;
  const sections = [...new Set(rows.map(r => r.section))];
  const esc = s => String(s).replace(/\|/g, "/");
  const L = ["# Full Agent Capability List: where each item stands", "",
    "Generated by `node scripts/capability-list.cjs`; do not edit. Source: the owner's list (`full-agent-capability-list-2026-10-11.md`, verbatim), mapped bullet by bullet in `map.cjs` to the capability registry. Status is derived from the registry, never typed.", "",
    "**PROVEN (live, with the provider's record): 0 of " + rows.length + ".** Nothing new is deployed and no live model call has succeeded yet.", "",
    "- **IN_PRODUCT**: a person can reach it on this branch today (chat flows, the planner's read tools, a deployed function), at least in part. Not proven live.",
    "- **MODULE_ONLY**: a domain module passes offline tests, but nothing in the chat or app calls it yet.",
    "- **GATED**: needs a licensed partner or provider that is not connected.",
    "- **NOT_BUILT**: no capability, or one only claimed in the registry.",
    "- **Coverage** says how much of the bullet the mapped capabilities would do once built (`part`: the note names the missing piece).", "",
    "**The document is incomplete as pasted:** it ends inside section 7 (\"Refunds and disputes\"), and the \"[Flag]\" section that the tags point to (\"see the last section\") is not included. Items after section 7 are not mapped.", "",
    "| Section | Items | PROVEN | IN_PRODUCT | MODULE_ONLY | GATED | NOT_BUILT | Clash with an owner rule |", "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ...sections.map(s => { const l = rows.filter(r => r.section === s); return `| ${s} | ${l.length} | ${ORDER.map(st => by(l, st)).join(" | ")} | ${l.filter(r => r.conflict).length} |`; }),
    `| **all** | **${rows.length}** | ${ORDER.map(st => `**${by(rows, st)}**`).join(" | ")} | **${rows.filter(r => r.conflict).length}** |`, "",
    "By tag: " + ["Read", "Ask", "Rule", "Built in", "Flag"].map(t => { const l = rows.filter(r => r.tags.includes(t)); return `[${t}] ${l.length} (in product ${by(l, "IN_PRODUCT")}, not built ${by(l, "NOT_BUILT")})`; }).join("; ") + ".", "",
    "## Items that clash with a standing owner rule as written", "",
    ...rows.filter(r => r.conflict).map(r => `- **${r.n}.** ${esc(r.text)} — ${r.conflict}.`), "",
    "## Alinea parity (owner's v4 roadmap)", "",
    "Status is derived: **not started** (no capability, or one only claimed), **built** (a module passes offline tests, nothing calls it), **wired** (reachable in chat or the scheduler on this branch, not proven live). **Approval-gated** means it places orders, each behind that person's fresh yes and the $5 cap.", "",
    "| Feature | Status | Approval-gated | Capabilities | Note |", "| --- | --- | --- | --- | --- |",
    ...parity().map(p => `| ${p.feature} | ${p.status} | ${p.gated ? "yes" : "no"} | ${p.ids.map(id => `${id} (${caps[id].status}${REACHABLE[id] ? ", reachable" : ""})`).join(", ") || "none"} | ${esc(p.note)} |`),
    `| **all** | ${["wired", "built", "not started"].map(st => `${st} ${parity().filter(p => p.status === st).length}`).join(", ")} | ${parity().filter(p => p.gated).length} | | |`, "",
    "## Every item", "", "| # | Item | Tags | Status | Coverage | Capabilities | Note |", "| --- | --- | --- | --- | --- | --- | --- |",
    ...rows.map(r => `| ${r.n} | ${esc(r.text)} | ${r.tags.join(", ")} | ${r.status} | ${r.coverage} | ${r.ids.map(id => `${id} (${caps[id].status}${REACHABLE[id] ? ", reachable" : ""})`).join(", ")} | ${esc(r.note)}${r.conflict ? `; **rule:** ${esc(r.conflict)}` : ""} |`), ""];
  return L.join("\n");
}
function parity() {
  return PARITY.map(([feature, ids, gated, note]) => {
    for (const id of ids) if (!caps[id]) throw new Error(`parity: unknown capability ${id}`);
    const built = ids.filter(id => !["CLAIMED", "NOT_BUILT", "NOT_WIRED"].includes(caps[id].status));
    const status = !built.length ? "not started" : ids.some(id => REACHABLE[id]) ? "wired" : "built";
    return { feature, ids, gated, note, status };
  });
}
if (require.main === module) {
  const { rows, problems } = build();
  if (problems.length) { console.error(problems.join("\n")); process.exit(1); }
  const out = render(rows), target = path.join(root, "docs/capability-list/README.md");
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== out) { console.error("docs/capability-list/README.md is stale: run node scripts/capability-list.cjs"); process.exit(1); }
    console.log(`capability list verified: ${rows.length} items; parity ${parity().map(p => p.status).join(", ")}`);
  } else {
    fs.writeFileSync(target, out);
    console.log(`capability list: ${rows.length} items; ` + ORDER.map(st => `${st} ${rows.filter(r => r.status === st).length}`).join(", ") + `; rule clashes ${rows.filter(r => r.conflict).length}`);
  }
}
module.exports = { parse, status, parity, build };
