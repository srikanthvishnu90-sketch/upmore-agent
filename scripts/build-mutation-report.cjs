#!/usr/bin/env node
// Mutation coverage report (overnight G4): every domain module in packages/domain, the planted defects that patch it
// (evals/depth/<ID>.mutations.cjs), and what the last depth run recorded for each (evals/depth/results/<ID>.json): the
// tagged test that caught it, or why it didn't. A module no planted defect touches is listed as a gap, never hidden.
//   node scripts/build-mutation-report.cjs            writes docs/depth/MUTATION-COVERAGE.md
//   node scripts/build-mutation-report.cjs --check    fails if the report is stale, a recorded result is missing, or
//                                                     a recorded defect did not bite
// It reads recorded results only; the runs themselves are `node evals/depth/run.cjs <ID>`.
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const depthDir = path.join(root, "evals/depth"), domainDir = path.join(root, "packages/domain");
const out = path.join(root, "docs/depth/MUTATION-COVERAGE.md");

function build() {
  const problems = [];
  const modules = fs.readdirSync(domainDir).filter(f => /^\d{2,3}-.*\.js$/.test(f)).sort();
  const packets = fs.readdirSync(depthDir).filter(f => f.endsWith(".mutations.cjs")).map(f => f.replace(".mutations.cjs", "")).sort();
  const byModule = Object.fromEntries(modules.map(m => [m, []]));
  const packetRows = [], repositoryRows = [];
  for (const id of packets) {
    const muts = require(path.join(depthDir, `${id}.mutations.cjs`));
    const resFile = path.join(depthDir, "results", `${id}.json`);
    const res = fs.existsSync(resFile) ? JSON.parse(fs.readFileSync(resFile, "utf8")) : null;
    if (!res) problems.push(`${id}: no recorded run (evals/depth/results/${id}.json); run node evals/depth/run.cjs ${id}`);
    const rec = Object.fromEntries(((res && res.rows) || []).map(r => [r.id, r]));
    let proven = 0;
    for (const m of muts) {
      const r = rec[m.id];
      const status = r ? r.status : "not recorded";
      if (r && r.status === "proven") proven++;
      else problems.push(`${id} ${m.id}: ${status}`);
      for (const p of m.patches) {
        if (m.scope === 'repository') { repositoryRows.push({file:p.file,packet:id,id:m.id,test:m.test,status}); continue; }
        if (!byModule[p.file]) { problems.push(`${id} ${m.id}: patches ${p.file}, which is not a domain module`); continue; }
        byModule[p.file].push({ packet: id, id: m.id, sub: m.sub, defect: m.defect, test: m.test, status });
      }
    }
    packetRows.push({ id, defects: muts.length, proven, subs: res ? res.sub_capabilities : null, baseline: res ? res.baseline_all_green : null });
  }
  // The eval harness's planted defects (doc 13, evals/mutations.cjs): caught by a whole layer, not one tagged test, and
  // proven by the CI step `node evals/runner.cjs --mutations` (every one must be caught and attributed), not recorded here.
  const evalMuts = require(path.join(root, "evals/mutations.cjs"));
  const agentMuts = (fs.readFileSync(path.join(root, "evals/agent/mutations.ts"), "utf8").match(/^\s*\{ *id: *"M\d+"/gm) || []).length;
  for (const m of evalMuts) for (const p of m.patches) if (byModule[p.file]) byModule[p.file].push({ packet: "EVAL", id: m.id, sub: m.layer, defect: m.title, test: "the eval harness's layer", status: "caught in CI (node evals/runner.cjs --mutations)" });
  const covered = modules.filter(m => byModule[m].length), gaps = modules.filter(m => !byModule[m].length);
  const esc = s => String(s).replace(/\|/g, "\\|");
  const lines = [
    "# Mutation coverage",
    "",
    "Generated by `node scripts/build-mutation-report.cjs` from `evals/depth/*.mutations.cjs` and the recorded runs in",
    "`evals/depth/results/` (overnight G4). A planted defect is a realistic bug patched into a copy of `packages/domain`;",
    "\"proven\" means its tagged test failed with the bug in place and passed without it. `--check` in CI fails on a stale",
    "report or a defect that did not bite. Results are as recorded by `node evals/depth/run.cjs <ID>`, not re-run here.",
    "",
    `**${covered.length} of ${modules.length} domain modules** have at least one planted defect; **${modules.length - covered.length}** have none (listed below as gaps).`,
    `**${packetRows.reduce((a, p) => a + p.proven, 0)} of ${packetRows.reduce((a, p) => a + p.defects, 0)}** planted defects across ${packetRows.length} depth packets are proven to bite; the eval harness adds ${evalMuts.length} more (\`node evals/runner.cjs --mutations\`, CI), and the testing agent ${agentMuts} in the chat layer (\`deno run -A evals/agent/mutations.ts\`, CI), which patch edge files, not domain modules.`,
    "",
    "## Depth packets",
    "",
    "| Packet | Sub-capabilities | Planted defects | Proven | Baseline green |",
    "| --- | --- | --- | --- | --- |",
    ...packetRows.map(p => `| ${p.id} | ${p.subs ?? "not run"} | ${p.defects} | ${p.proven} | ${p.baseline === null ? "not run" : p.baseline ? "yes" : "NO"} |`),
    "",
    "## Modules with planted defects",
    "",
    "| Module | Defect | Planted bug | Caught by (tagged test) | Status |",
    "| --- | --- | --- | --- | --- |",
    ...covered.flatMap(m => byModule[m].map(d => `| ${m} | ${d.packet} ${d.id} | ${esc(d.defect)} | ${d.sub}: ${esc(d.test)} | ${d.status} |`)),
    "",
    "## Repository files with planted defects",
    "",
    "These packets exercise the staged production entry outside packages/domain. They are counted as defects above, never as domain-module coverage. Their canonical patches and recorded runner evidence remain required.",
    "",
    "| File | Defect | Tagged test | Status |",
    "| --- | --- | --- | --- |",
    ...repositoryRows.map(r=>`| ${r.file} | ${r.packet} ${r.id} | ${esc(r.test)} | ${r.status} |`),
    "",
    "## Gaps: modules no planted defect touches",
    "",
    "Their own unit tests still run in `node --test tests/*.cjs`; what is missing is proof that those tests catch a realistic bug.",
    "",
    ...gaps.map(m => `- ${m}`),
    "",
  ];
  return { text: lines.join("\n"), problems, covered: covered.length, modules: modules.length };
}

const r = build();
if (process.argv.includes("--check")) {
  const cur = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
  if (cur !== r.text) r.problems.push("docs/depth/MUTATION-COVERAGE.md is stale; run node scripts/build-mutation-report.cjs");
  if (r.problems.length) { console.error(r.problems.join("\n")); process.exit(1); }
  console.log(`mutation coverage verified: ${r.covered}/${r.modules} modules with planted defects, every recorded defect proven`);
} else {
  fs.writeFileSync(out, r.text);
  console.log(`mutation coverage: ${r.covered}/${r.modules} modules with planted defects${r.problems.length ? `; problems:\n${r.problems.join("\n")}` : ""}`);
}
