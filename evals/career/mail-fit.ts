// WO-043: fits the intent scorer's weights (MAIL_BIAS, MAIL_WEIGHTS in supabase/functions/_shared/career_mail.ts) on the
// tuning splits ONLY: "tune", "tune2", "dev3" (mail-labels.json) and "dev4" (mail-dev4.json). It never reads devcheck,
// holdout, blind40 or dev4check. Multinomial logistic regression, full batch, fixed steps, zero start, L2: deterministic,
// no model, no network. Each feature is one intent family (or a rule hit, or a sender prior); its weight per kind is
// printed so a reader can see why a message scored as it did.
// Run: deno run --allow-read evals/career/mail-fit.ts            prints the table
//      deno run --allow-read --allow-write evals/career/mail-fit.ts --write   writes it between the markers
import { classifyMail, MAIL_BIAS, MAIL_DECISION, MAIL_KINDS, MAIL_WEIGHTS, mailFeatures, type MailKind } from "../../supabase/functions/_shared/career_mail.ts";
import labels from "./mail-labels.json" with { type: "json" };
import dev4 from "./mail-dev4.json" with { type: "json" };

export const TUNING_SPLITS = ["tune", "tune2", "dev3", "dev4"];
export const FIT = { steps: 4000, rate: 0.5, l2: Number(Deno.args[Deno.args.indexOf("--l2") + 1] ?? 0) || 0.004 };

export function tuningMails() {
  return [...labels.mails, ...dev4.mails].filter((m) => TUNING_SPLITS.includes(m.split));
}

export function fit(mails = tuningMails()) {
  const rows: { f: string[]; y: number }[] = [];
  for (const m of mails) {
    const f = mailFeatures(m);
    if (f) rows.push({ f: [...f.keys()], y: MAIL_KINDS.indexOf(m.expect.kind as MailKind) });
  }
  const vocab = [...new Set(rows.flatMap((r) => r.f))].sort();
  const K = MAIL_KINDS.length, V = vocab.length, at = new Map(vocab.map((v, i) => [v, i]));
  const W = Array.from({ length: V }, () => new Float64Array(K)), b = new Float64Array(K);
  const X = rows.map((r) => r.f.map((v) => at.get(v)!));
  for (let step = 0; step < FIT.steps; step++) {
    const gW = Array.from({ length: V }, () => new Float64Array(K)), gb = new Float64Array(K);
    rows.forEach((r, i) => {
      const z = Array.from(b);
      for (const j of X[i]) for (let k = 0; k < K; k++) z[k] += W[j][k];
      const top = Math.max(...z), e = z.map((v) => Math.exp(v - top)), s = e.reduce((a, c) => a + c, 0);
      for (let k = 0; k < K; k++) {
        const g = e[k] / s - (k === r.y ? 1 : 0);
        gb[k] += g;
        for (const j of X[i]) gW[j][k] += g;
      }
    });
    for (let k = 0; k < K; k++) b[k] -= FIT.rate * gb[k] / rows.length;
    for (let j = 0; j < V; j++) for (let k = 0; k < K; k++) W[j][k] -= FIT.rate * (gW[j][k] / rows.length + FIT.l2 * W[j][k]);
  }
  const round = (x: number) => Math.round(x * 100) / 100;
  const keep = (row: Float64Array) => Object.fromEntries(MAIL_KINDS.map((k, i) => [k, round(row[i])]).filter(([, w]) => Math.abs(w as number) >= 0.05));
  return { rows: rows.length, bias: keep(b), weights: Object.fromEntries(vocab.map((v, j) => [v, keep(W[j])])) };
}

export function table(r: ReturnType<typeof fit>): string {
  const obj = (o: Record<string, unknown>) => "{ " + Object.entries(o).map(([k, v]) => `${k}: ${v}`).join(", ") + " }";
  return [
    `// BEGIN MAIL_WEIGHTS (generated by evals/career/mail-fit.ts from ${r.rows} tuning emails; steps ${FIT.steps}, rate ${FIT.rate}, l2 ${FIT.l2})`,
    `export const MAIL_BIAS: Partial<Record<MailKind, number>> = ${obj(r.bias)};`,
    `export const MAIL_WEIGHTS: Record<string, Partial<Record<MailKind, number>>> = {`,
    ...Object.entries(r.weights).map(([k, v]) => `  "${k}": ${obj(v)},`),
    `};`,
    `// END MAIL_WEIGHTS`,
  ].join("\n");
}

// --cv: k-fold cross-validation inside the tuning splits (fold = FNV-1a of the id mod 4): weights fitted on three folds
// score the fourth, so the number says how the WEIGHTS generalise. The families themselves were written while reading the
// tuning splits, so this is still optimistic; only dev4check (scored once) says how the whole reader generalises.
function crossValidate() {
  const fnv = (s: string) => { let h = 0x811c9dc5; for (const c of new TextEncoder().encode(s)) { h ^= c; h = Math.imul(h, 0x01000193) >>> 0; } return h; };
  const mails = tuningMails(), keepW = { ...MAIL_WEIGHTS }, keepB = { ...MAIL_BIAS };
  const at = Deno.args.indexOf("--share");
  if (at >= 0) MAIL_DECISION.minShare = Number(Deno.args[at + 1]);
  const n = () => ({ predicted: 0, right: 0, labeled: 0, found: 0, rejAsInterview: 0 });
  const by: Record<string, ReturnType<typeof n>> = { all: n(), "tune+tune2+dev3": n(), dev4: n() };
  for (let fold = 0; fold < 4; fold++) {
    const r = fit(mails.filter((m) => fnv(m.id + "wo-043-cv") % 4 !== fold));
    for (const k of Object.keys(MAIL_WEIGHTS)) delete MAIL_WEIGHTS[k];
    Object.assign(MAIL_WEIGHTS, r.weights);
    for (const k of Object.keys(MAIL_BIAS)) delete MAIL_BIAS[k as MailKind];
    Object.assign(MAIL_BIAS, r.bias);
    for (const m of mails.filter((m) => fnv(m.id + "wo-043-cv") % 4 === fold)) {
      const got = classifyMail(m).kind, want = m.expect.kind;
      if (got !== want && Deno.args.includes("--misses")) console.log(`  out-of-fold MISS ${m.id} [${m.split}]: want ${want}, got ${got} -- ${m.subject}`);
      for (const c of [by.all, by[m.split === "dev4" ? "dev4" : "tune+tune2+dev3"]]) {
        if (got !== "other") { c.predicted++; if (got === want) c.right++; }
        if (want !== "other") { c.labeled++; if (got === want) c.found++; }
        if (want === "rejection" && got === "interview") c.rejAsInterview++;
      }
    }
  }
  for (const k of Object.keys(MAIL_WEIGHTS)) delete MAIL_WEIGHTS[k];
  Object.assign(MAIL_WEIGHTS, keepW);
  for (const k of Object.keys(MAIL_BIAS)) delete MAIL_BIAS[k as MailKind];
  Object.assign(MAIL_BIAS, keepB);
  const pct = (a: number, b: number) => `${(100 * a / b).toFixed(1)}% (${a}/${b})`;
  for (const [name, c] of Object.entries(by)) {
    console.log(`4-fold CV, ${name}: status precision ${pct(c.right, c.predicted)}, recall ${pct(c.found, c.labeled)}, rejection read as interview ${c.rejAsInterview}`);
  }
}

if (import.meta.main && Deno.args.includes("--cv")) crossValidate();
else if (import.meta.main) {
  const t = table(fit());
  if (Deno.args.includes("--write")) {
    const path = new URL("../../supabase/functions/_shared/career_mail.ts", import.meta.url);
    const src = Deno.readTextFileSync(path);
    const next = src.replace(/\/\/ BEGIN MAIL_WEIGHTS[\s\S]*?\/\/ END MAIL_WEIGHTS/, t);
    Deno.writeTextFileSync(path, next);
    console.log(`wrote ${t.split("\n").length} lines`);
  } else console.log(t);
}
