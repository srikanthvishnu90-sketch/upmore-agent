#!/usr/bin/env python3
"""Build evals/gauntlet/standalone/run-gauntlet.cjs: the live gauntlet runner and its three corpora in ONE file, so the
owner can run it from any shell with only Node 18+ (no clone, no install). One-way: edit evals/gauntlet/run-live.cjs and
the corpus JSON files, then rerun. `--check` fails when the built file is stale (tests/gauntlet-runner.test.cjs)."""
import argparse, json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
g = root / "evals/gauntlet"
embed = {n: json.loads((g / n).read_text()) for n in ["sloppy-20.json", "spec16-20.json", "l3-adversarial.json"]}
runner = (g / "run-live.cjs").read_text()
if runner.startswith("#!"):
    runner = runner.split("\n", 1)[1]
content = ("#!/usr/bin/env node\n"
           "// GENERATED by scripts/build-standalone-gauntlet.py from evals/gauntlet/run-live.cjs and its corpora. Do not edit.\n"
           "// Usage (Node 18+, any machine that can reach the function):\n"
           "//   UPMORE_CHAT_URL=https://<project>.supabase.co/functions/v1/agent-chat UPMORE_TEST_JWT=<token> \\\n"
           "//     node run-gauntlet.cjs --suite sloppy|spec16|l3 --label live-<date>\n"
           "// Results (every reply verbatim) are written to ./results/ next to this file. The JWT is read from the environment\n"
           "// only; it is never written to a file or printed.\n"
           "globalThis.__UPMORE_GAUNTLET_EMBED__ = " + json.dumps(embed, separators=(",", ":"), ensure_ascii=False) + ";\n"
           + runner)
target = g / "standalone/run-gauntlet.cjs"
ap = argparse.ArgumentParser(); ap.add_argument("--check", action="store_true"); args = ap.parse_args()
if args.check:
    if not target.exists() or target.read_text() != content:
        raise SystemExit("standalone gauntlet is stale: run python3 scripts/build-standalone-gauntlet.py")
    print("standalone gauntlet verified")
else:
    target.write_text(content); target.chmod(0o755); print(f"built {target.relative_to(root)} ({len(content)} bytes)")
