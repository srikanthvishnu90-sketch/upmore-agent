// Generator for the stage-4.5 deliverable: builds
// ~/workspace/your_files/upmore-career-300-rerun-results.md and
// results-index.json SOLELY from the per-scenario record.json files.
// Also resolves each scenario's run-1 "Before" bubble from
// ~/workspace/your_files/upmore-career-conversations/ by content overlap
// (never by filename trust alone) and selects 30 highlight conversations.
"use strict";
const fs = require("fs");
const path = require("path");
const ROOT300 = path.join(process.env.HOME, "workspace/your_files/upmore-career-gauntlet-300");
const RUN1 = path.join(process.env.HOME, "workspace/your_files/upmore-career-conversations");
const OUT_MD = path.join(process.env.HOME, "workspace/your_files/upmore-career-300-rerun-results.md");

const ids = Array.from({ length: 300 }, (_, i) => "SC-" + String(i + 1).padStart(3, "0"));
const records = new Map();
for (const id of ids) {
  const p = path.join(ROOT300, id, "record.json");
  if (!fs.existsSync(p)) { console.error("MISSING RECORD", id); process.exit(2); }
  records.set(id, JSON.parse(fs.readFileSync(p, "utf8")));
}
// --- run-1 resolution -------------------------------------------------------
function firstAgentBubble(md) {
  for (const line of md.split("\n")) {
    const m = line.match(/^\*\*AGENT:\*\*\s?(.*)$/);
    if (m && m[1].trim()) return m[1].trim();
  }
  return null;
}
const run1Cache = new Map();
function run1For(id, ask) {
  if (run1Cache.has(id)) return run1Cache.get(id);
  let best = null;
  const toks = new Set(String(ask).toLowerCase().replace(/[^a-z0-9 ]/g, " ").split(/\s+/).filter((w) => w.length > 3));
  for (const f of fs.readdirSync(RUN1)) {
    if (!f.startsWith(id + "-") || !f.endsWith(".md")) continue;
    const md = fs.readFileSync(path.join(RUN1, f), "utf8");
    const bubble = firstAgentBubble(md);
    if (!bubble) continue;
    const hay = (f + " " + md.slice(0, 4000)).toLowerCase();
    let score = 0; for (const t of toks) if (hay.includes(t)) score++;
    if (!best || score > best.score) best = { file: f, bubble, score };
  }
  run1Cache.set(id, best);
  return best;
}
const trunc280 = (s) => (s.length > 280 ? s.slice(0, 280).trimEnd() + " […truncated]" : s);
// --- totals -----------------------------------------------------------------
const byFamily = new Map(); const overall = {}; let unsafe = 0; const evClass = {};
for (const id of ids) {
  const r = records.get(id);
  const fam = r.family || "unknown";
  if (!byFamily.has(fam)) byFamily.set(fam, {});
  byFamily.get(fam)[r.verdict] = (byFamily.get(fam)[r.verdict] || 0) + 1;
  byFamily.get(fam)._n = (byFamily.get(fam)._n || 0) + 1;
  overall[r.verdict] = (overall[r.verdict] || 0) + 1;
  if (r.safety_verdict !== "SAFE") unsafe++;
  evClass[r.evidence_class || "E2"] = (evClass[r.evidence_class || "E2"] || 0) + 1;
}
const vline = (o) => ["PASS", "FAIL", "BLOCKED", "NOT IMPLEMENTED", "INCONCLUSIVE"].filter((v) => o[v]).map((v) => `${v} ${o[v]}`).join(" · ") || "none";
// --- highlights: 30, spread across families, incl. failures/refusals/GAPs ----
function pickHighlights() {
  const picks = []; const used = new Set();
  const add = (id) => { if (id && !used.has(id) && picks.length < 30) { used.add(id); picks.push(id); } };
  const fams = [...byFamily.keys()];
  for (const fam of fams) { // one PASS per family if any
    add(ids.find((id) => records.get(id).family === fam && records.get(id).verdict === "PASS"));
  }
  for (const fam of fams) add(ids.find((id) => records.get(id).family === fam && records.get(id).verdict === "FAIL"));
  for (const fam of fams) add(ids.find((id) => records.get(id).family === fam && records.get(id).verdict === "NOT IMPLEMENTED"));
  for (const id of ids) { const r = records.get(id); if (r.doorstep && r.doorstep.driven_by === "gap") { add(id); if (picks.length >= 18) break; } }
  for (const id of ["SC-035", "SC-248", "SC-294", "SC-295", "SC-296", "SC-300"]) add(id); // refusals / kill switch
  for (let i = 0; picks.length < 30 && i < ids.length; i += 10) add(ids[i]);
  for (const id of ids) { if (picks.length >= 30) break; add(id); }
  return picks.slice(0, 30);
}
const highlights = pickHighlights();
// --- document ---------------------------------------------------------------
const L = [];
L.push("# Upmore Career — 300-Scenario Grand Re-Run Results (Stage 4.5)", "");
L.push(`Build under test: **7be2759** (integrated R1+R2+R3 repairs) · Fixture version: gauntlet-v1 · Tier: **HARNESS-tier** (staging harness path; no career agent is deployed) · One trial per scenario · Persona: gauntlet fixture P1 for every scenario.`, "");
L.push("Every reply below is the verbatim delivered bubble text from the product chat path (143 containment → 120 → 130 → 142 → 141, composed by 140). Grading is computed (reply oracle + rail-state assertions + §7.1 checks), never literal. Generated by `scripts/career/gauntlet/gen-grand.cjs` from the per-scenario record.json files — not hand-typed.", "");
L.push("## Totals", "");
L.push(`**Overall (denominator 300): ${vline(overall)}**`, "");
L.push(`Evidence classes: ${Object.entries(evClass).map(([k, v]) => `${k} ${v}`).join(" · ")} (E2 = full staging path with controlled sinks; no scenario in this run performed a live public read, so none is labeled E3).`, "");
L.push(`Safety: ${unsafe === 0 ? "SAFE 300/300 — no §7.1 critical failure occurred" : `UNSAFE in ${unsafe}/300 — see those records`}. Safety is scored separately from task verdicts.`, "");
L.push("| Family | n | Verdicts |", "|---|---|---|");
for (const [fam, o] of byFamily) L.push(`| ${fam} | ${o._n} | ${vline(o)} |`);
L.push("", "## Per-scenario results", "");
let changed = 0, noRun1 = 0;
for (const id of ids) {
  const r = records.get(id);
  const ask = r.canonical_ask;
  L.push(`## ${id} — ${r.family}`, "");
  L.push(`**Ask:** ${ask}`, "");
  L.push(`**Reply (verbatim, as delivered):**`, "");
  const bubbles = r.delivered_messages || [];
  if (!bubbles.length) L.push("*(No agent bubble was delivered.)*", "");
  for (const b of bubbles) L.push(`> ${String(b).replace(/\n/g, "\n> ")}`, "");
  const failed = (r.assertions || []).filter((a) => !a.pass).map((a) => a.id).join(", ") || "none";
  L.push(`**Verdict: ${r.verdict}** — safety: ${r.safety_verdict}. Basis: ${r.verdict_derivation ? r.verdict_derivation.rule_fired : ""} (oracle hard fails: ${(r.oracle && r.oracle.failures || []).map((f) => f.rule).join(", ") || "none"}; failed assertions: ${failed}). Evidence: ${r.evidence_class}; latency ${r.latency_ms} ms (staging wall-time).`, "");
  if (r.doorstep) {
    if (r.doorstep.driven_by === "agent") L.push(`Doorstep: driven by agent — step log: \`${id}/doorstep/step-log.json\`, final screenshot: \`${id}/doorstep/final-doorstep.png\`, payload snapshot: \`${id}/doorstep/payload-snapshot.json\`.`, "");
    else L.push(`Doorstep: **GAP** — ${r.doorstep.gap} (step log: \`${id}/doorstep/step-log.json\`).`, "");
  }
  const r1 = run1For(id, ask);
  const todayFirst = bubbles[0] || null;
  if (!r1) { noRun1++; L.push(`Before (run 1): no run-1 transcript on file.`, ""); }
  else if (todayFirst && r1.bubble !== todayFirst) { changed++; L.push(`Before (run 1, from ${r1.file}): ${trunc280(r1.bubble)}`, ""); }
  else L.push(`Before (run 1, from ${r1.file}): unchanged — first bubble identical to today's.`, "");
}
L.push("## Highlights — 30 full verbatim conversations", "");
L.push("Selected to spread across all families and to include failures, refusals, and doorstep GAP cases — not only wins.", "");
for (const id of highlights) {
  const r = records.get(id);
  L.push(`### ${id} — ${r.family} — verdict ${r.verdict}`, "");
  const users = r.input_messages || []; const agents = r.delivered_messages || [];
  // records store inputs and bubbles as separate arrays; the transcript.md is
  // the interleaved source — quote it conversation section verbatim.
  const tmd = fs.readFileSync(path.join(ROOT300, id, "transcript.md"), "utf8");
  const sec = tmd.split("## Conversation")[1].split("## Verdict")[0].trim();
  L.push(sec, "");
}
fs.writeFileSync(OUT_MD, L.join("\n"));
// --- index ------------------------------------------------------------------
const index = {};
for (const id of ids) {
  const r = records.get(id);
  index[id] = { verdict: r.verdict, safety: r.safety_verdict, oracle_fails: (r.oracle && r.oracle.failures || []).map((f) => f.rule), evidence_class: r.evidence_class || "E2", record_path: `upmore-career-gauntlet-300/${id}/record.json`, family: r.family, canonical_ask_sha256_16: r.canonical_ask_sha256_16 };
}
fs.writeFileSync(path.join(ROOT300, "results-index.json"), JSON.stringify(index, null, 2) + "\n");
console.log(JSON.stringify({ overall, unsafe, evClass, highlights: highlights.length, changed, noRun1, families: [...byFamily.keys()] }, null, 2));
