// Builds extension/lib/trainee-core.js from extension/src/core.ts: the apply stack's own planner, question map, answer
// keys and payload hash, bundled for the browser (WO-031). Run from anywhere:
//   deno run -A extension/build.ts           write the bundle
//   deno run -A extension/build.ts --check   exit 1 when the checked-in bundle is not what the sources build
// The bundle is checked in so the extension loads unpacked with no build step; --check keeps it honest.
const root = new URL("..", import.meta.url).pathname;
const out = root + "extension/lib/trainee-core.js";
const tmp = await Deno.makeTempDir({ prefix: "trainee-bundle-" });
try {
  const r = await new Deno.Command(Deno.execPath(), {
    args: ["bundle", "--quiet", "--platform", "browser", "--format", "iife", "-o", tmp + "/trainee-core.js", "extension/src/core.ts"],
    cwd: root,
    stdout: "inherit",
    stderr: "inherit",
  }).output();
  if (!r.success) throw Error("deno bundle failed");
  const header = "// GENERATED by extension/build.ts from extension/src/core.ts. Do not edit; run `deno run -A extension/build.ts`.\n";
  const built = header + (await Deno.readTextFile(tmp + "/trainee-core.js"));
  if (Deno.args.includes("--check")) {
    let current = "";
    try {
      current = await Deno.readTextFile(out);
    } catch { /* missing */ }
    if (current !== built) {
      console.error("extension/lib/trainee-core.js is stale: run `deno run -A extension/build.ts` and commit it.");
      Deno.exit(1);
    }
    console.log("extension/lib/trainee-core.js is fresh.");
  } else {
    await Deno.mkdir(root + "extension/lib", { recursive: true });
    await Deno.writeTextFile(out, built);
    console.log("wrote extension/lib/trainee-core.js (" + built.length + " bytes)");
  }
} finally {
  await Deno.remove(tmp, { recursive: true });
}
