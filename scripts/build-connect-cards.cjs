#!/usr/bin/env node
// Connect cards (owner, 2026-10-11): builds what makes a connect link look like the owner's reference screenshot.
//   connect/<provider>.html    the page behind https://<app>/connect/<provider>. iMessage reads its og:title
//                              ("Connect Alpaca to Trainee") and og:image and draws the preview card itself (title and domain
//                              in the grey strip); a person who opens it is sent on to the app, which starts that connection.
//   img/connect/<provider>.png 1200x630: dark grey, the company's real logo in the middle and the Trainee wordmark centered
//                              right below it, in Trainee purple, in Libre Baskerville (a Baskerville serif).
//                              The app's chat draws the same card from the same image.
// Providers and their real logos come from packages/domain/76-connect-cards.js and img/brands/ (SOURCES.md).
//   node scripts/build-connect-cards.cjs            write the pages, and the images (needs Playwright + Chromium)
//   node scripts/build-connect-cards.cjs --check    fail when a page is stale or an image is missing or the wrong size
const fs = require("node:fs"), path = require("node:path"), { execSync } = require("node:child_process");
const root = path.resolve(__dirname, "..");
const CC = require(path.join(root, "packages/domain/76-connect-cards.js"));
const esc = s => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

function page(p) {
  const name = CC.PROVIDERS[p].name, title = CC.title(p), link = CC.url(p), image = `${CC.DEFAULT_BASE}/${CC.PROVIDERS[p].card}`;
  // No og:description, so the preview is the title and the domain only, as in the reference.
  return `<!doctype html>
<!-- Generated by scripts/build-connect-cards.cjs; do not edit. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>${esc(title)}</title>
<meta property="og:type" content="website">
<meta property="og:site_name" content="Trainee">
<meta property="og:title" content="${esc(title)}">
<meta property="og:url" content="${esc(link)}">
<meta property="og:image" content="${esc(image)}">
<meta property="og:image:type" content="image/png">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="630">
<meta property="og:image:alt" content="${esc(name)} logo">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="${esc(title)}">
<meta name="twitter:image" content="${esc(image)}">
<link rel="icon" href="/icon-192.png">
<style>
  body { margin: 0; min-height: 100vh; display: grid; place-items: center; background: #0B0B0D; font: 15px/1.4 -apple-system, BlinkMacSystemFont, "Segoe UI", sans-serif; }
  a { display: block; width: min(320px, 86vw); border-radius: 18px; overflow: hidden; background: #2C2C2E; color: #F2F2F7; text-decoration: none; }
  img { display: block; width: 100%; height: auto; background: #1E1F22; }
  b { display: block; padding: 10px 14px 0; font-weight: 600; }
  span { display: block; padding: 2px 14px 11px; color: #A1A1A6; font-size: 13px; white-space: nowrap; overflow: hidden; text-overflow: ellipsis; }
</style>
</head>
<body>
<a href="/?connect=${p}"><img src="/${CC.PROVIDERS[p].card}" alt="${esc(name)} logo" width="1200" height="630"><b>${esc(title)}</b><span>${esc(CC.host(link))}</span></a>
<script>location.replace("/?connect=${p}");</script>
</body>
</html>
`;
}

// The image, drawn in Chromium from the real logo file and the bundled typeface.
function imageHtml(p) {
  const svg = fs.readFileSync(path.join(root, CC.PROVIDERS[p].icon), "utf8");
  // Owner, 2026-10-11: a dark grey card, the wordmark in a serif: Libre Baskerville (fonts/libre-baskerville-regular.woff2,
  // SIL OFL 1.1, fonts/libre-baskerville-OFL.txt), bundled so the image renders the same on every machine.
  // Owner, 2026-10-20: the same grey card for Trainee; the wordmark reads Trainee, in purple instead of green. #9B7BB8 is
  // the mid tone of Trainee's plum scale (site/index.html: --plum #4A2F5E, gradient #7A5A93, --plum-light #D4C2E2), chosen
  // because the plum itself is unreadable on this grey (1.3:1) and #9B7BB8 matches the old green's contrast (4.2-5.1:1).
  const font = "file://" + path.join(root, "fonts/libre-baskerville-regular.woff2");
  return `<!doctype html><html><head><style>
  @font-face { font-family: "Libre Baskerville"; font-weight: 400; src: url("${font}") format("woff2"); }
  html, body { margin: 0; width: 1200px; height: 630px; background: linear-gradient(160deg, #26282B 0%, #161719 100%); overflow: hidden; }
  body { display: flex; flex-direction: column; align-items: center; justify-content: center; gap: 30px; }
  .logo { width: 172px; height: 172px; }
  .logo svg { width: 100%; height: 100%; display: block; }
  .word { font: 400 72px/1 "Libre Baskerville", Baskerville, Georgia, serif; letter-spacing: 0.5px; color: #9B7BB8; }
  </style></head><body><div class="logo">${svg}</div><div class="word">Trainee</div></body></html>`;
}

// img/brands/SOURCES.md, from img/brands/brands.json: every real logo in the app, where it came from, under what license.
function sources() {
  const brands = JSON.parse(fs.readFileSync(path.join(root, "img/brands/brands.json"), "utf8"));
  return [
    "# Brand icons: real company logos only",
    "",
    "Generated from `img/brands/brands.json` by `node scripts/build-connect-cards.cjs`; do not edit.",
    "",
    "Owner rule (2026-10-11, a must): every company Upmore shows is shown with its real logo, never a generic glyph, a letter",
    "tile, an emoji or a look-alike. Each file is the company's own mark, taken unmodified from an open icon collection that",
    "redistributes it (the trademark stays the company's; it is shown only to name the company). Single-colour marks are in",
    "the brand's own colour. A company with no file here is shown by name only, never with a stand-in.",
    "",
    "Left out on purpose after review: Spectrum, Xfinity, Progressive and Fidelity (the marks found could not be confirmed",
    "as those companies' current logos), Grubhub (no longer in Simple Icons), SimpleFIN (not reachable from this environment).",
    "Add the official file and a row in brands.json to bring one in.",
    "",
    "| File | Company | Matches | Taken from | License of the collection |",
    "| --- | --- | --- | --- | --- |",
    ...brands.map(b => `| ${path.basename(b.file)} | ${b.name} | ${b.match.join(", ")} | ${b.from} (${b.collection}, ${b.url}) | ${b.license} |`),
    "",
  ].join("\n");
}

function pngSize(file) {
  const b = fs.readFileSync(file);
  if (b.length < 24 || b.toString("ascii", 1, 4) !== "PNG") return null;
  return { width: b.readUInt32BE(16), height: b.readUInt32BE(20) };
}

if (require.main === module) {
  const providers = Object.keys(CC.PROVIDERS);
  const problems = [];
  for (const p of providers) {
    if (!fs.existsSync(path.join(root, CC.PROVIDERS[p].icon))) problems.push(`${p}: no real logo at ${CC.PROVIDERS[p].icon}`);
    if (!JSON.parse(fs.readFileSync(path.join(root, "img/brands/brands.json"), "utf8")).some(b => b.file === CC.PROVIDERS[p].icon)) problems.push(`${p}: ${CC.PROVIDERS[p].icon} has no entry in img/brands/brands.json`);
  }
  if (problems.length) { console.error(problems.join("\n")); process.exit(1); }

  if (process.argv.includes("--check")) {
    if (fs.readFileSync(path.join(root, "img/brands/SOURCES.md"), "utf8") !== sources()) problems.push("img/brands/SOURCES.md is stale");
    for (const p of providers) {
      const f = path.join(root, "connect", `${p}.html`);
      if (!fs.existsSync(f) || fs.readFileSync(f, "utf8") !== page(p)) problems.push(`connect/${p}.html is stale`);
      const s = fs.existsSync(path.join(root, CC.PROVIDERS[p].card)) ? pngSize(path.join(root, CC.PROVIDERS[p].card)) : null;
      if (!s || s.width !== 1200 || s.height !== 630) problems.push(`${CC.PROVIDERS[p].card} is missing or not 1200x630`);
    }
    if (problems.length) { console.error(problems.join("\n") + "\nrun node scripts/build-connect-cards.cjs"); process.exit(1); }
    console.log(`connect cards verified: ${providers.join(", ")}`);
  } else {
    fs.mkdirSync(path.join(root, "connect"), { recursive: true });
    fs.mkdirSync(path.join(root, "img/connect"), { recursive: true });
    fs.writeFileSync(path.join(root, "img/brands/SOURCES.md"), sources());
    for (const p of providers) fs.writeFileSync(path.join(root, "connect", `${p}.html`), page(p));
    let chromium;
    for (const id of ["playwright", process.env.PLAYWRIGHT_MODULE, "/opt/node-tools/node_modules/playwright", () => execSync("npm root -g").toString().trim() + "/playwright"]) {
      try { if (id) { ({ chromium } = require(typeof id === "function" ? id() : id)); break; } } catch { /* next */ }
    }
    if (!chromium) { console.log(`pages written; images NOT built (Playwright not found: set PLAYWRIGHT_MODULE)`); process.exit(2); }
    (async () => {
      const browser = await chromium.launch();
      const pg = await browser.newPage({ viewport: { width: 1200, height: 630 }, deviceScaleFactor: 1 });
      for (const p of providers) {
        const tmp = path.join(require("node:os").tmpdir(), `trainee-connect-${p}.html`);
        fs.writeFileSync(tmp, imageHtml(p));
        await pg.goto("file://" + tmp);
        await pg.evaluate(() => document.fonts.ready);
        await pg.screenshot({ path: path.join(root, CC.PROVIDERS[p].card) });
        fs.unlinkSync(tmp);
      }
      await browser.close();
      console.log(`connect cards built: ${providers.map(p => `connect/${p}.html + ${CC.PROVIDERS[p].card}`).join(", ")}`);
    })().catch(e => { console.error(e.message); process.exit(1); });
  }
}
module.exports = { page, imageHtml, sources };
