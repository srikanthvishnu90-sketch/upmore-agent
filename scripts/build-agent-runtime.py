#!/usr/bin/env python3
"""Bundle unchanged pure domain modules for Deno's shared lexical runtime.

No network, credentials, execution adapters or status overrides are added.
--check compares bytes without writing; --root supports isolated fixture trees.
"""
import argparse
import hashlib
import json
from pathlib import Path

MODULES = (
    ('33-agent-monitors.js', 'AgentMonitors'),
    ('35-agent-intents.js', 'AgentIntents'),
    ('36-agent-workflows.js', 'AgentWorkflows'),
    ('41-agent-recovery.js', 'AgentRecovery'),
    ('43-agent-loop.js', 'AgentLoop'),
    ('44-agent-earn.js', 'AgentEarn'),
    ('45-advice-guard.js', 'AdviceGuard'),
    ('46-voice.js', 'AgentVoice'),
    ('47-data-guard.js', 'DataGuard'),
    ('48-money-math.js', 'MoneyMath'),
    ('49-agent-save.js', 'AgentSave'),
    ('53-compliance.js', 'Compliance'),
    ('54-agent-money.js', 'AgentMoney'),
    ('55-agent-news.js', 'AgentNews'),
    ('56-agent-proactive.js', 'AgentProactive'),
    ('57-agent-ledger.js', 'AgentLedger'),
    ('58-agent-control.js', 'AgentControl'),
    ('59-agent-alerts.js', 'AgentAlerts'),
    ('60-agent-money-plans.js', 'AgentMoneyPlans'),
)
OUTPUT = Path('supabase/functions/_shared/agent_runtime.js')


def build(root):
    paths = [Path('packages/domain') / name for name, _ in MODULES]
    paths += [Path('packages/capabilities/registry.js'), Path('packages/capabilities/registry.json')]
    source_bytes = [(path, (root / path).read_bytes()) for path in paths]
    manifest = [{'path': path.as_posix(), 'sha256': hashlib.sha256(raw).hexdigest()}
                for path, raw in source_bytes]
    encoded = json.dumps(manifest, ensure_ascii=False, sort_keys=True, separators=(',', ':'))
    source_hash = hashlib.sha256(encoded.encode('utf-8')).hexdigest()
    registry = json.loads(source_bytes[-1][1])
    if not isinstance(registry, dict) or not isinstance(registry.get('capabilities'), list):
        raise ValueError('Registry snapshot lacks a capabilities array')
    blocks = ['// GENERATED by scripts/build-agent-runtime.py; edit its unchanged source inputs through their owner.\n'
              '// Shared lexical order matches the domain CJS/VM dependency contract; no financial effects are wired.\n'
              f'const RuntimeSourceHash = {json.dumps(source_hash)};\n'
              f'const RuntimeSources = {encoded};\n']
    for path, raw in source_bytes[:-1]:
        blocks.append(f'\n// BEGIN {path.as_posix()}\n' + raw.decode('utf-8') +
                      f'\n// END {path.as_posix()}\n')
    names = [name for _, name in MODULES] + ['CapabilityRegistry']
    blocks.append('\n// Fail at import rather than silently running a feed with missing dependencies.\n'
                  'for (const [name, value] of Object.entries({' + ', '.join(names) + '})) {\n'
                  '  if (!value || typeof value !== "object") throw new Error("Missing runtime dependency: " + name);\n'
                  '}\n'
                  'function runtimeDeepFreeze(value) {\n'
                  '  if (value && typeof value === "object") {\n'
                  '    for (const child of Object.values(value)) runtimeDeepFreeze(child);\n'
                  '    Object.freeze(value);\n'
                  '  }\n'
                  '  return value;\n'
                  '}\n'
                  'const RuntimeRegistryData = runtimeDeepFreeze(' +
                  json.dumps(registry, ensure_ascii=False, sort_keys=True, separators=(',', ':')) + ');\n'
                  'runtimeDeepFreeze(RuntimeSources);\n'
                  'const runtimeRegistryErrors = CapabilityRegistry.validate(RuntimeRegistryData);\n'
                  'if (runtimeRegistryErrors.length) throw new Error("Invalid runtime registry: " + runtimeRegistryErrors.join("; "));\n'
                  'export { ' + ', '.join(names + ['RuntimeRegistryData', 'RuntimeSourceHash', 'RuntimeSources']) + ' };\n')
    return ''.join(blocks).encode('utf-8'), source_hash


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    try:
        output, digest = build(args.root)
    except (OSError, ValueError, UnicodeError) as error:
        parser.exit(1, f'Runtime build failed: {error}\n')
    target = args.root / OUTPUT
    if args.check:
        if not target.is_file() or target.read_bytes() != output:
            parser.exit(1, 'Agent runtime is stale or missing; run scripts/build-agent-runtime.py.\n')
        print(f'PASS: agent runtime matches unchanged sources and registry ({digest}).')
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(output)
        print(f'Built {OUTPUT.as_posix()} ({len(output)} bytes; source SHA256 {digest}).')


if __name__ == '__main__':
    main()
