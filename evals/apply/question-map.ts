// WO-020: how well the question map reads real application questions.
//   precision  of the questions it placed (anything but unknown), the share placed on the same fact as the hand label
//   recall     of the questions the labeler placed, the share the map placed on the same fact
// Labels: evals/apply/question-labels.json, written by an independent labeler blind to the map, over a random sample of
// 240 required questions (evals/apply/question-sample.json). Coverage: every required question of both captured samples
// by kind; a posting is ready when none of its required questions is unknown (screens, attestations, consents and essays
// go in the approval, nothing is left to ask in a later text).
//   deno run --allow-read --allow-write evals/apply/question-map.ts [--write docs/apply/question-map.md]
import { mapQuestion } from "../../supabase/functions/_shared/question_map.ts";
import { fileAlternative } from "../../supabase/functions/_shared/career_apply.ts";

export interface Labeled { id: string; fact: string; kind: string }
export function score(sample: { questions: any[] }, labels: { labels: Labeled[] }) {
  const byId = new Map(labels.labels.map((l) => [l.id, l]));
  let placed = 0, placedRight = 0, labeled = 0, labeledHit = 0, fills = 0, fillsRight = 0;
  const wrong: { id: string; label: string; got: string; want: string }[] = [];
  for (const q of sample.questions) {
    const l = byId.get(q.id);
    if (!l) throw new Error(`no label for ${q.id}`);
    const m = mapQuestion({ label: q.label, type: q.type, options: (q.options || []).map((x: string) => ({ label: x })) });
    if (m.fact !== "unknown") { placed++; if (m.fact === l.fact) placedRight++; }
    // A fill writes a value with no one looking first (fact, derived, file); everything else is shown in the approval.
    if (["fact", "derived", "file"].includes(m.kind)) { fills++; if (m.fact === l.fact) fillsRight++; }
    if (l.fact !== "unknown") { labeled++; if (m.fact === l.fact) labeledHit++; }
    if (m.fact !== l.fact) wrong.push({ id: q.id, label: q.label.slice(0, 120), got: m.fact, want: l.fact });
  }
  return { n: sample.questions.length, placed, precision: placed ? placedRight / placed : 0, recall: labeled ? labeledHit / labeled : 0, fills, fill_precision: fills ? fillsRight / fills : 0, wrong };
}

export function coverage(set: { postings: any[] }) {
  const kinds: Record<string, number> = {};
  const left: number[] = [];
  let required = 0;
  for (const p of set.postings.filter((x: any) => !x.reason)) {
    let unknown = 0;
    for (const f of p.fields) {
      if (!f.required || fileAlternative(f, p.fields)) continue;
      required++;
      const m = mapQuestion({ label: f.label, type: f.type, options: f.options || [] });
      kinds[m.kind] = (kinds[m.kind] || 0) + 1;
      if (m.kind === "unknown") unknown++;
    }
    left.push(unknown);
  }
  left.sort((a, b) => a - b);
  return { postings: left.length, required, kinds, median_left: left[Math.floor(left.length / 2)] ?? 0, ready: left.filter((x) => x === 0).length, at_most_2: left.filter((x) => x <= 2).length };
}

