const assert = require('node:assert/strict');
const Track = require('../../packages/domain/126-career-track.js');
const now = Date.UTC(2030, 0, 2, 12);
const company = 'Invented Lantern Loom';
const store = Track.createMemoryStore([]);
Track.addApplication(store, { app_id: 'invented-app-1', company, role: 'Paper Systems Engineer', stage: 'Submitted' }, { now });
Track.addApplication(store, { app_id: 'invented-app-2', company, role: 'Ribbon Infrastructure Engineer', stage: 'Submitted' }, { now });
const selected = Track.findByCompany(store, company);
assert.equal(selected.app_id, 'invented-app-1');
const receipt = Track.manualUpdate(store, company, 'Offer', { now, app_id: 'invented-app-2', role: 'Woven Platform Engineer' });
assert.equal(receipt.application.app_id, 'invented-app-1');
assert.equal(receipt.application.role, 'Paper Systems Engineer');
assert.equal(store.rows[1].stage, 'Submitted');
assert.equal(receipt.application, store.rows[0]);
const unique = Track.createMemoryStore([]);
Track.addApplication(unique, { app_id: 'invented-unique', company: 'Invented Amber Kites', role: 'Fabric Operations Analyst', stage: 'Submitted' }, { now });
const moved = Track.manualUpdate(unique, 'Invented Amber Kites', 'Interview rounds', { now });
assert.equal(moved.application.app_id, 'invented-unique');
assert.equal(moved.application.stage, 'Interview rounds');
assert.equal(moved.application.role, 'Fabric Operations Analyst');
assert.equal(moved.application.events.at(-1).source, 'user-reported');
