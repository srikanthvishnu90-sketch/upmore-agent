// SC-016 Find 60 quant traders at prop shops with competition-math backgrounds
"use strict";
const L = require("./_w01-lib.cjs"); const { M, H } = L;
(async () => {
  const s = H.session("SC-016", "outreach-60-quant-traders-competition-math");
  const user = L.USERS.alex, profile = L.PROFILES.alex;
  s.user("Find 60 quant traders at prop shops with competition-math backgrounds");
  const q = M.parseTarget("Find 60 quant traders at prop trading firms", profile);
  s.tool("124.parseTargetSpec", q);
  const firms = L.FIRM_SETS.sets.quant.firms.filter(f => f.status !== "historical").map(f => f.name);
  const COMPS = ["Putnam competition", "IMO training camp", "USAMO", "national math olympiad", "competition math (ARML)"];
  const records = L.generate(100, firms, (i) => ({ title: i % 4 === 3 ? "Quantitative Researcher" : "Quant Trader", seniority_band: "analyst", geography: ["New York", "Chicago"][i % 2], office: ["New York", "Chicago"][i % 2], schools: [["MIT", "TEST University", "Princeton University", "University of Chicago"][i % 4]], competition: COMPS[i % COMPS.length], has_competition_math: i % 5 !== 4, factKind: "competition" }), 1616);
  await L.verifyPool(records, L.fixtureVerifier());
  const sourced = records.filter(c => c.has_competition_math);
  s.tool("sourcing filter (competition-math background, public bios seam over fixtures)", { in: records.length, out: sourced.length, competitions: COMPS });
  const supp = M.createSuppressionStore();
  const pool = M.buildList(sourced, { count: 60, firms, role_family: "quant" }, { profile, suppression: supp, userId: "u-alex", nowMs: L.NOW });
  const card = M.listReviewCard(pool, q);
  s.tool("124.buildList", { yield: pool.yield }); s.card({ title: "List review — 60 quant traders, competition-math", ...card });
  const { drafts, tiers, gatePass } = L.draftAll(pool.selected, user);
  s.tool("124.draftAndGate", { drafted: drafts.length, gate_pass: gatePass, tiers });
  L.sampleDrafts(s, drafts, 2, "SC-016");
  s.user("Approved");
  const campaign = M.createCampaign({ id: "sc016-campaign", userId: "u-alex", approved: true });
  M.enqueue(campaign, pool.selected.map((c, i) => ({ candidate: c, draft: drafts[i] })), { suppression: supp });
  const plan = M.planWave(campaign, { waveNumber: 1, seed: 16 });
  const transport = L.testTransport();
  const sentRes = await M.sendPending(campaign, { transport, suppression: supp, maxItems: plan.scheduled, nowIso: L.NOW_ISO });
  s.tool("124.sendPending (TEST transport)", { days: plan.days, ...sentRes });
  s.verify("60 selected, all competition-math, across real quant firm set", { selected: pool.selected.length, firms: Object.keys(card.breakdown.by_firm).length, all_comp: pool.selected.every(c => c.has_competition_math), gate_pass: gatePass, sent_wave1: sentRes.sent });
  const ok = pool.selected.length === 60 && gatePass === 60 && sentRes.sent === plan.scheduled;
  await s.finish({ status: ok ? "COMPLETE" : "LEARN", outcome: `60 quant traders at prop shops (real 8-firm quant set) with competition-math backgrounds selected, drafted (gate 60/60) and wave-1 sent via TEST seed inbox. People/backgrounds were labeled TEST fixtures.`, reason: ok ? undefined : "counts off", unblock: ok ? undefined : "inspect pool" });
})();
