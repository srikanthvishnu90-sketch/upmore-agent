#!/usr/bin/env python3
"""Bundle the domain modules the extension-sync edge function needs.

The extension-sync function (supabase/functions/extension-sync) serves the
signed-in user their saved answers — module 149's deriveAnswers over their
own confirmed 122 profile — and records employer-confirmation reports as
module 126 tracker records. Deno cannot load the packages/domain files
directly (they are plain scripts shared with the node tests), so — exactly
like scripts/build-router-core.py does for agent-chat — this script
concatenates the three modules into one ES module the function imports.

One-way: edit packages/domain, then rerun.
    python3 scripts/build-extension-sync.py           rebuild
    python3 scripts/build-extension-sync.py --check   fail if the bundle is stale
"""
import argparse
from pathlib import Path

root = Path(__file__).resolve().parents[1]
names = ["122-career-profile.js", "126-career-track.js", "149-career-portal-apply.js"]
exports = ["CareerProfile", "CareerTrack", "CareerPortalApply"]

content = "// Generated by scripts/build-extension-sync.py; edit packages/domain instead.\n"
content += "\n".join((root / "packages/domain" / n).read_text() for n in names)
content += "\nexport { " + ", ".join(exports) + " };\n"

parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
target = root / "supabase/functions/_shared/extension_domain.js"
if args.check:
    if not target.exists() or target.read_text() != content:
        raise SystemExit("Extension-sync domain bundle is stale: %s (run python3 scripts/build-extension-sync.py)" % target.relative_to(root))
    print("Extension-sync domain bundle verified")
else:
    target.write_text(content)
    print("Extension-sync domain bundle built: %d modules, %d bytes" % (len(names), len(content)))
